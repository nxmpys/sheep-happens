const DICTIONARIES: Record<Locale, Record<UiKey, string>> = { es, en };

/** Translates a UI key, replacing `{name}` placeholders with `vars`. */
export function t(locale: Locale, key: UiKey, vars: Record<string, string | number> = {}): string {
  const template = DICTIONARIES[locale][key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

export function useTranslations(locale: Locale) {
  return (key: UiKey, vars?: Record<string, string | number>) => t(locale, key, vars);
}

const DATE_LOCALES: Record<Locale, string> = { es: 'es-ES', en: 'en-GB' };

/** Formats a calendar date (no time zone shifts: dates are stored as UTC midnight). */
export function formatDate(locale: Locale, date: Date): string {
  return new Intl.DateTimeFormat(DATE_LOCALES[locale], {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(date);
}

/** Short calendar date for compact lines: "16 oct 2026", "16 Oct 2026". */
export function formatShortDate(locale: Locale, date: Date): string {
  // Some ICU versions write "16 oct. 2026" or "16 de oct de 2026": keep it short and plain.
  return new Intl.DateTimeFormat(DATE_LOCALES[locale], { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' })
    .format(date)
    .replace(/ de /g, ' ')
    .replace(/\.(?= )/, '');
}

/** Formats an instant in UTC: "4 de noviembre de 2026, 23:00 UTC". */
export function formatUtcTime(locale: Locale, date: Date): string {
  const day = new Intl.DateTimeFormat(DATE_LOCALES[locale], { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(date);
  const time = new Intl.DateTimeFormat(DATE_LOCALES[locale], { hour: '2-digit', minute: '2-digit', hourCycle: 'h23', timeZone: 'UTC' }).format(date);
  return `${day}, ${time} UTC`;
}

/** Formats an instant in Spain's time zone (CET/CEST): "5 de noviembre de 2026, 00:00 CET". */
export function formatSpainTime(locale: Locale, date: Date): string {
  const day = new Intl.DateTimeFormat(DATE_LOCALES[locale], {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'Europe/Madrid',
  }).format(date);
  const time = new Intl.DateTimeFormat(DATE_LOCALES[locale], {
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
    timeZone: 'Europe/Madrid',
    timeZoneName: 'short',
  })
    .format(date)
    .replace(' ', ' '); // keep "00:00 CET" on one line
  return `${day}, ${time}`;
}
