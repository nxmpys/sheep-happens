const DICTIONARIES: Record<Locale, Record<UiKey, string>> = { es, en };

/** Translates a UI key, replacing `{name}` placeholders with `vars`. */
export function t(locale: Locale, key: UiKey, vars: Record<string, string | number> = {}): string {
  const template = DICTIONARIES[locale][key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

export function useTranslations(locale: Locale) {
  return (key: UiKey, vars?: Record<string, string | number>) => t(locale, key, vars);
}

const DATE_LOCALES: Record<Locale, string> = { es: 'es-ES', en: 'en-GB' };

/** Formats a calendar date (no time zone shifts: dates are stored as UTC midnight). */
export function formatDate(locale: Locale, date: Date): string {
  return new Intl.DateTimeFormat(DATE_LOCALES[locale], {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
    timeZone: 'UTC',
  }).format(date);
}
